#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEMP_DIR=""

cleanup() {
  if [ -n "$TEMP_DIR" ]; then
    rm -rf "$TEMP_DIR"
  fi
}

fail() {
  echo "public task routing matrix step summary smoke failed: $*" >&2
  exit 1
}

require_literal() {
  local file="$1"
  local literal="$2"
  local description="$3"

  if ! grep -Fq -- "$literal" "$file"; then
    fail "$file is missing $description"
  fi
}

main() {
  local summary_json
  local step_summary

  TEMP_DIR="$(mktemp -d)"
  trap cleanup EXIT INT TERM

  summary_json="$TEMP_DIR/public-task-routing-matrix-summary.json"
  step_summary="$TEMP_DIR/step-summary.md"

  cat >"$summary_json" <<'EOF'
