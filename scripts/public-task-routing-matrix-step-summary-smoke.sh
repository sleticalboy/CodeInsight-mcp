      "expect_file": "docs/task-routing-expectations/express.tsv",
      "summary_json": "<output-dir>/express/summary.json",
      "task_count": 4,
      "expectation_count": 4,
      "total_task_source_lines": 800,
      "total_selected_lines": 100,
      "total_estimated_tokens": 1800,
      "max_impacted_files": 9,
      "routes": [
