  GITHUB_STEP_SUMMARY="$step_summary" \
    "$ROOT_DIR/scripts/public-task-routing-matrix-step-summary.sh" \
      "$summary_json" \
      codeinsight-public-routing-snapshot \
      https://example.com/artifact \
      https://example.com/run >/dev/null

  require_literal "$step_summary" "## Public Task Routing Matrix" "summary heading"
